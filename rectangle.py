def area(a, b): 

    '''
    Принимает стороны прямоугольника a (int/float) и b (int/float)
    
    Возращает площадь прямоугольника (int/float)
    '''

    return a * b 

def perimeter(a, b):

    '''
    Принимает стороны прямоугольника a (int/float) и b (int/float)
        
    Возращает площадь прямоугольника (int/float)
    '''

    return (a + b) * 2 
