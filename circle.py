import math


def area(r):

    '''
    Принимает радиус круга r (int/float)

    Возвращает площадь круга (float)
    '''

    return math.pi * r * r
    

def perimeter(r):

    '''
    Принимает радиус круга r (int/float)
    
    Возвращает периметр круга (float)
    '''

    return 2 * math.pi * r

