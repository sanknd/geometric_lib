def area(a, h): 

    '''
    Принимает сторону треугольника a (int/float) и высоту h (int/float)
                
    Возращает площадь треугольника (float)
    '''

    return a * h / 2 

def perimeter(a, b, c): 

    '''
    Принимает стороны треугольника a (int/float), b (int/float), c (int/float)
                    
    Возращает периметр треугольника (int/float)
    '''

    return a + b + c 
